//! `eval/RECORDING.md`: the script for the person recording the clips.

use crate::manifest::Manifest;

pub fn render(manifest: &Manifest) -> String {
    let mut out = String::from(
        "# Recording the eval clips\n\n\
         Generated by `cargo run -p whimpr-eval -- --write-recording eval/RECORDING.md`. Do not edit by hand; \
         edit `eval/fixtures/manifest.json` instead.\n\n\
         ## How\n\n\
         - Save each clip into `eval/fixtures/` with **exactly** the file name shown. Any WAV works: 16-bit or \
         float, any sample rate, mono or stereo (16 kHz mono is ideal).\n\
         - One take each, at your normal pace and volume, sitting where you normally dictate. Leave about half a \
         second of quiet before and after, **except** the *very-short* clips, where you start right away and stop immediately.\n\
         - Say the words in the **Say** column. Don't read the punctuation aloud; say \"new line\" only where it's written.\n\
         - Quiet room for everything except the *noisy* clip.\n\
         - Check progress any time: `cargo run -p whimpr-eval -- --list-missing`.\n\n\
         The eval dictionary contains: ",
    );
    let words: Vec<&str> = manifest.dictionary.iter().map(|d| d.correct.as_str()).collect();
    out.push_str(&words.join(", "));
    out.push_str(".\n\n");

    let mut category = "";
    for f in &manifest.fixtures {
        if f.category != category {
            category = &f.category;
            out.push_str(&format!("\n## {category}\n\n| File | Say |\n|---|---|\n"));
        }
        let say = if f.say.is_empty() { "*(say nothing)*".to_string() } else { format!("\"{}\"", f.say) };
        let note = f.note.as_deref().map_or(String::new(), |n| format!(" — {n}"));
        out.push_str(&format!("| `{}` | {say}{note} |\n", f.wav));
    }
    out.push('\n');
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn lists_each_clip_under_its_category_with_the_exact_file_name() {
        let m = Manifest::parse(
            r#"{"dictionary":[{"correct":"ChargeBee"}],"fixtures":[
                {"id":"01","wav":"01-filler-a.wav","category":"filler","say":"um hello"},
                {"id":"02","wav":"02-filler-b.wav","category":"filler","say":"so yeah"},
                {"id":"03","wav":"03-silence-a.wav","category":"silence","say":"","note":"3 s of room tone","expect":"no_output"}]}"#,
        )
        .unwrap();
        let md = render(&m);
        assert_eq!(md.matches("## filler").count(), 1);
        for needle in ["`01-filler-a.wav` | \"um hello\"", "`02-filler-b.wav`", "## silence", "*(say nothing)* — 3 s of room tone", "ChargeBee"] {
            assert!(md.contains(needle), "{needle}\n{md}");
        }
    }
}
